#!/usr/bin/env python3
"""
calibrate_role.py - offline calibration of role-aware Proteus (handoff section 6, tests 7-8).
No API calls. Writes role_contrast/calibration/calibration_results.json and calibration_summary.md.

Scripted subjects, 200-round sessions, both roles:
  iid       independent fair coin                         1,000 sessions per role (test 7)
  all_T     always TRIANGLE                                 200 sessions per role (test 8)
  alt       strict alternation T S T S ...                  200 sessions per role (test 8)
  wsls      win-stay / lose-shift on the role's own outcome 200 sessions per role (outcome-contingent)
  bias70    TRIANGLE with p = .70, independent              200 sessions per role
Seeds: opponent random.Random("paca-role-contrast-v1-calibration|<agent>|<role>|<i>|opp"), subject
"...|subj". Results are deterministic.

    python role_contrast/calibrate_role.py
"""
import json, math, os, random, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import role_proteus as RX     # noqa: E402

N = 200
AGENTS = {"iid": 1000, "all_T": 200, "alt": 200, "wsls": 200, "bias70": 200}


def play(args):
    agent, role, i = args
    key = f"paca-role-contrast-v1-calibration|{agent}|{role}|{i}"
    ro, rs = random.Random(key + "|opp"), random.Random(key + "|subj")
    opp = RX.RoleProteus(role)
    wins, act, cpuT, chosT, winT, nT, detect = 0, 0, 0, 0, 0, 0, [0] * 9
    sel = [0] * 9; first = [None] * 9
    last_c, last_w = None, None
    w_by_quarter = [0, 0, 0, 0]
    for t in range(N):
        d = opp.decide(ro)
        if agent == "iid": c = "T" if rs.random() < .5 else "S"
        elif agent == "bias70": c = "T" if rs.random() < .7 else "S"
        elif agent == "all_T": c = "T"
        elif agent == "alt": c = "T" if t % 2 == 0 else "S"
        elif agent == "wsls": c = ("T" if rs.random() < .5 else "S") if last_c is None else (last_c if last_w else RX.other(last_c))
        w = opp.update(c, d.cpu)
        wins += w; w_by_quarter[t * 4 // N] += w
        act += any(r.sig for r in d.results); cpuT += d.cpu == "T"
        for k, r in enumerate(d.results):
            detect[k] += r.sig
            if r.sig and first[k] is None: first[k] = t + 1
        if d.pred is not None: sel[d.pred.n] += 1
        if c == "T": nT += 1; winT += w
        last_c, last_w = c, bool(w)
    return dict(agent=agent, role=role, i=i, win=wins / N, activation=act / N, opp_T=cpuT / N,
                win_when_T=(winT / nT if nT else None), win_when_S=((wins - winT) / (N - nT) if N - nT else None),
                channel_activation=[x / N for x in detect], selected=[x / N for x in sel],
                win_by_quarter=[x / (N // 4) for x in w_by_quarter])


def ci(x):
    x = np.asarray([v for v in x if v is not None], float)
    m = float(x.mean()); h = float(stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / math.sqrt(len(x)))
    return dict(mean=m, ci95=[m - h, m + h], sd=float(x.std(ddof=1)), n=len(x))


def main():
    jobs = [(a, r, i) for a, n in AGENTS.items() for r in RX.ROLES for i in range(n)]
    with ProcessPoolExecutor(max_workers=min(16, os.cpu_count() or 4)) as ex:
        res = list(ex.map(play, jobs, chunksize=20))
    out = {}
    lines = ["# Role-aware Proteus calibration (offline, no API calls)", "",
             f"200-round sessions. Generated by `role_contrast/calibrate_role.py`; deterministic seeds.", "",
             "| agent | role | sessions | subject win (95% CI) | activation | opponent P(T) | win when T / when S | win, rounds 151-200 |",
             "|---|---|---|---|---|---|---|---|"]
    for a in AGENTS:
        for r in RX.ROLES:
            rr = [x for x in res if x["agent"] == a and x["role"] == r]
            s = dict(n_sessions=len(rr), win=ci([x["win"] for x in rr]), activation=ci([x["activation"] for x in rr]),
                     opp_T=ci([x["opp_T"] for x in rr]), win_when_T=ci([x["win_when_T"] for x in rr]),
                     win_when_S=(ci([x["win_when_S"] for x in rr]) if any(x["win_when_S"] is not None for x in rr) else None),
                     win_last_quarter=ci([x["win_by_quarter"][3] for x in rr]),
                     win_by_quarter=[float(np.mean([x["win_by_quarter"][q] for x in rr])) for q in range(4)],
                     channel_activation=[float(np.mean([x["channel_activation"][k] for x in rr])) for k in range(9)],
                     selected=[float(np.mean([x["selected"][k] for x in rr])) for k in range(9)])
            out[f"{a}|{r}"] = s
            ws = "-" if s["win_when_S"] is None else f"{s['win_when_S']['mean']:.3f}"
            lines.append(f"| {a} | {r} | {len(rr)} | {s['win']['mean']:.4f} [{s['win']['ci95'][0]:.4f}, {s['win']['ci95'][1]:.4f}] | "
                         f"{s['activation']['mean']:.3f} | {s['opp_T']['mean']:.3f} | {s['win_when_T']['mean']:.3f} / {ws} | "
                         f"{s['win_last_quarter']['mean']:.3f} |")
    iid = {r: out[f"iid|{r}"] for r in RX.ROLES}
    checks = {
        "iid_ci_contains_0.5": {r: iid[r]["win"]["ci95"][0] <= .5 <= iid[r]["win"]["ci95"][1] for r in RX.ROLES},
        "iid_no_side_advantage": {r: abs(iid[r]["win_when_T"]["mean"] - iid[r]["win_when_S"]["mean"]) < .01 for r in RX.ROLES},
        "iid_opponent_side_balanced": {r: abs(iid[r]["opp_T"]["mean"] - .5) < .01 for r in RX.ROLES},
        "exploits_all_T": {r: out[f"all_T|{r}"]["win"]["mean"] < .2 for r in RX.ROLES},
        "exploits_alt": {r: out[f"alt|{r}"]["win"]["mean"] < .3 for r in RX.ROLES},
        "exploits_wsls": {r: out[f"wsls|{r}"]["win"]["mean"] < .45 for r in RX.ROLES},
        "exploits_bias70": {r: out[f"bias70|{r}"]["win"]["mean"] < .45 for r in RX.ROLES},
    }
    ok = all(all(v.values()) for v in checks.values())
    lines += ["", "Null channel activation per channel (iid), matcher / mismatcher:", ""]
    for k in range(9):
        lines.append(f"- channel {k}: {iid['matcher']['channel_activation'][k]:.4f} / {iid['mismatcher']['channel_activation'][k]:.4f}")
    lines += ["", "Checks: " + ", ".join(f"{k} {'PASS' if all(v.values()) else 'FAIL'}" for k, v in checks.items()),
              "", f"Overall: {'PASS' if ok else 'FAIL'}"]
    os.makedirs(os.path.join(HERE, "calibration"), exist_ok=True)
    json.dump(dict(results=out, checks=checks, all_ok=ok), open(os.path.join(HERE, "calibration", "calibration_results.json"), "w"), indent=1)
    open(os.path.join(HERE, "calibration", "calibration_summary.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
