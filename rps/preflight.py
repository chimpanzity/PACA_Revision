#!/usr/bin/env python3
r"""
preflight.py - PACA-RPS v1 checks before the pilot and the real run.

    python rps/preflight.py         -> rps/preflight_result.json (exit code non-zero on failure)

  1. both frozen system prompts hash to rps_prompts.EXPECTED_SHA256;
  2. run_config.json is regenerated byte-for-byte by make_config.py (schedule integrity);
  3. 28 round-1 requests (7 models x 2 prompts x temperature 0 and 1) through the real client:
     each must return a parsed model choice with finish_reason == "stop".
Records served model, provider, tokens and latency per call.

Temperature caveat (known before this study): the 13 Nov 2026 manipulation check
(temp2x2_replication/manipulation_check/) found that OpenRouter has no endpoint that accepts
temperature for anthropic/claude-opus-4.8, openai/gpt-5.4 and openai/gpt-5.4-mini; for those the
requested value is sent but not applied. The request still carries it, as in the temp2x2 study.
"""
import datetime, hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rps_prompts as RP                       # noqa: E402
import make_config as MC                       # noqa: E402
from rps_client import make_client, call_rps   # noqa: E402

TEMP_NOT_APPLIED = {"anthropic/claude-opus-4.8", "openai/gpt-5.4", "openai/gpt-5.4-mini"}


def main():
    ok_all = True
    print("Prompt hashes:")
    for m in ("minimalist", "informed"):
        same = hashlib.sha256(RP.get_system_prompt(m).encode("utf-8")).hexdigest() == RP.EXPECTED_SHA256[m]
        ok_all &= same; print(f"  {m:11s} {'MATCH' if same else 'DIFFERENT - stop'}")
    cfgp = os.path.join(HERE, "run_config.json")
    regen = json.dumps(MC.build(), indent=1)
    same = open(cfgp, encoding="utf-8").read() == regen
    ok_all &= same
    print(f"run_config.json regenerates byte-for-byte: {same}  (sha256 {hashlib.sha256(open(cfgp, 'rb').read()).hexdigest()[:16]})")

    key = os.environ.get("OPENROUTER_API_KEY")
    if not key:
        print("ERROR: OPENROUTER_API_KEY not set."); sys.exit(2)
    client = make_client(key, timeout=120)
    user = RP.build_prompt([], 5, 25)
    rows = []
    print("\nModels (round-1 request, both prompts, temperature 0 and 1):")
    for e in MC.MODELS:
        disp, fam, slug = e[0], e[1], e[2]
        probs, served, prov = [], set(), set()
        for mode in ("minimalist", "informed"):
            for temp in (0.0, 1.0):
                r = call_rps(client, slug, RP.get_system_prompt(mode), user, temp)
                served.add(r.served_model or "?"); prov.add(r.provider or "?")
                if r.status != "model" or r.finish_reason != "stop":
                    probs.append(f"{mode}@{temp}: {r.status} finish={r.finish_reason} {r.error_message[:100]}")
                rows.append(dict(slug=slug, prompt_mode=mode, temperature=temp, status=r.status, choice=r.choice,
                                 last_line_choice=r.last_line_choice, served_model=r.served_model, provider=r.provider,
                                 finish_reason=r.finish_reason, completion_tokens=r.completion_tokens,
                                 reasoning_tokens=r.reasoning_tokens, prompt_tokens=r.prompt_tokens,
                                 latency_ms=r.latency_ms, n_attempts=r.n_attempts, error=r.error_message,
                                 response_text=r.response_text))
        status = "OK" if not probs else "FAIL"
        ok_all &= not probs
        note = "  [temperature not applied by any endpoint]" if slug in TEMP_NOT_APPLIED else ""
        print(f"  [{status:4s}] {slug:32s} served={sorted(served)} provider={sorted(prov)}{note}")
        for p in probs: print(f"         problem: {p}")
    out = os.path.join(HERE, "preflight_result.json")
    json.dump(dict(checked_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(), all_ok=bool(ok_all),
                   temperature_not_applied=sorted(TEMP_NOT_APPLIED), calls=rows), open(out, "w", encoding="utf-8"), indent=1)
    print(f"\n{'ALL CHECKS PASSED.' if ok_all else 'SOMETHING FAILED - do not start the pilot.'}  -> {out}")
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
