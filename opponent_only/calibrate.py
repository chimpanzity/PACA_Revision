#!/usr/bin/env python3
"""
calibrate.py - offline calibration of the July matcher Proteus with matcher scoring (handoff section 7.4).
No API calls. Writes opponent_only/calibration/calibration_results.json and calibration_summary.md.
These are sanity checks of the opponent, not LLM evidence.

Scripted subjects, 200-round sessions, through oo_proteus (= protean_committed.choose_opponent_move):
  iid      independent fair coin              1,000 sessions per condition label (M, O; the opponent
                                              and scoring are identical, so the two are replicates)
  all_T    always TRIANGLE                      200 sessions
  all_S    always STAR                          200 sessions
  alt      strict alternation T S T S ...       200 sessions
  wsls     win-stay / lose-shift                200 sessions
  bias70   TRIANGLE with p = .70, independent   200 sessions
Seeds: opponent random.Random("paca-opponent-only-v1-calibration|<agent>|<label>|<i>|opp"), subject
"...|subj". Deterministic. Also reports the null envelope used in the figure: the central 95% range of
(a) one iid session's win rate and (b) the mean of 4 iid sessions (a model's cell mean).

    python opponent_only/calibrate.py
"""
import json, math, os, random, sys
from concurrent.futures import ProcessPoolExecutor
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import oo_proteus as X     # noqa: E402

N = 200
JOBS = [("iid", "M", 1000), ("iid", "O", 1000), ("all_T", "-", 200), ("all_S", "-", 200),
        ("alt", "-", 200), ("wsls", "-", 200), ("bias70", "-", 200)]


def runs_z(ch):
    n = len(ch); n1 = ch.count("T"); n2 = n - n1
    if n1 == 0 or n2 == 0: return 0.0
    R = 1 + sum(1 for i in range(1, n) if ch[i] != ch[i - 1])
    mu = 2 * n1 * n2 / n + 1; var = 2 * n1 * n2 * (2 * n1 * n2 - n) / (n * n * (n - 1))
    return (R - mu) / math.sqrt(var) if var > 0 else 0.0


def play(args):
    agent, label, i = args
    key = f"paca-opponent-only-v1-calibration|{agent}|{label}|{i}"
    ro, rs = random.Random(key + "|opp"), random.Random(key + "|subj")
    opp = X.Proteus()
    wins = act = cpuT = 0; detect = [0] * 9; sel = [0] * 9; ch = ""
    last_c = last_w = None
    for t in range(N):
        d = opp.decide(ro)
        if agent == "iid": c = "T" if rs.random() < .5 else "S"
        elif agent == "bias70": c = "T" if rs.random() < .7 else "S"
        elif agent == "all_T": c = "T"
        elif agent == "all_S": c = "S"
        elif agent == "alt": c = "T" if t % 2 == 0 else "S"
        elif agent == "wsls": c = ("T" if rs.random() < .5 else "S") if last_c is None else (last_c if last_w else X.other(last_c))
        w = opp.update(c, d.cpu); wins += w; ch += c
        act += any(r.sig for r in d.results); cpuT += d.cpu == "T"
        for k, r in enumerate(d.results): detect[k] += r.sig
        if d.pred is not None: sel[d.pred.n] += 1
        last_c, last_w = c, bool(w)
    return dict(agent=agent, label=label, i=i, win=wins / N, activation=act / N, opp_T=cpuT / N,
                runs_z=runs_z(ch), channel_activation=[x / N for x in detect], selected=[x / N for x in sel])


def ci(x):
    x = np.asarray(x, float); m = float(x.mean())
    h = float(stats.t.ppf(.975, len(x) - 1) * x.std(ddof=1) / math.sqrt(len(x))) if len(x) > 1 else float("nan")
    return dict(mean=m, ci95=[m - h, m + h], sd=float(x.std(ddof=1)) if len(x) > 1 else 0.0, n=len(x))


def main():
    jobs = [(a, lab, i) for a, lab, n in JOBS for i in range(n)]
    with ProcessPoolExecutor(max_workers=min(16, os.cpu_count() or 4)) as ex:
        res = list(ex.map(play, jobs, chunksize=20))
    out = {}
    lines = ["# Matcher Proteus calibration (offline, no API calls)", "",
             "200-round sessions; July `protean_committed` matcher Proteus with matcher scoring. "
             "Generated by `opponent_only/calibrate.py`; deterministic seeds. Sanity checks, not LLM evidence.", "",
             "| agent | label | sessions | subject win (95% CI of mean) | session SD | any-channel activation | opponent P(T) |",
             "|---|---|---|---|---|---|---|"]
    for a, lab, n in JOBS:
        rr = [x for x in res if x["agent"] == a and x["label"] == lab]
        s = dict(n_sessions=len(rr), win=ci([x["win"] for x in rr]), activation=ci([x["activation"] for x in rr]),
                 opp_T=ci([x["opp_T"] for x in rr]), runs_z=ci([x["runs_z"] for x in rr]),
                 channel_activation=[float(np.mean([x["channel_activation"][k] for x in rr])) for k in range(9)],
                 selected=[float(np.mean([x["selected"][k] for x in rr])) for k in range(9)])
        out[f"{a}|{lab}"] = s
        lines.append(f"| {a} | {lab} | {len(rr)} | {s['win']['mean']:.4f} [{s['win']['ci95'][0]:.4f}, {s['win']['ci95'][1]:.4f}] | "
                     f"{s['win']['sd']:.4f} | {s['activation']['mean']:.3f} | {s['opp_T']['mean']:.3f} |")
    iid = np.array([x["win"] for x in res if x["agent"] == "iid"])
    r = np.random.default_rng(20261115)
    means4 = iid[r.integers(0, len(iid), size=(200000, 4))].mean(axis=1)
    env = dict(n_iid_sessions=int(len(iid)), session_q025=float(np.quantile(iid, .025)),
               session_q975=float(np.quantile(iid, .975)), mean4_q025=float(np.quantile(means4, .025)),
               mean4_q975=float(np.quantile(means4, .975)), session_sd=float(iid.std(ddof=1)),
               runs_z_q025=float(np.quantile([x["runs_z"] for x in res if x["agent"] == "iid"], .025)),
               runs_z_q975=float(np.quantile([x["runs_z"] for x in res if x["agent"] == "iid"], .975)))
    checks = {
        "iid_M_ci_contains_0.5": out["iid|M"]["win"]["ci95"][0] <= .5 <= out["iid|M"]["win"]["ci95"][1],
        "iid_O_ci_contains_0.5": out["iid|O"]["win"]["ci95"][0] <= .5 <= out["iid|O"]["win"]["ci95"][1],
        "iid_opponent_side_balanced": abs(out["iid|M"]["opp_T"]["mean"] - .5) < .01 and abs(out["iid|O"]["opp_T"]["mean"] - .5) < .01,
        "exploits_all_T": out["all_T|-"]["win"]["mean"] < .2,
        "exploits_all_S": out["all_S|-"]["win"]["mean"] < .2,
        "exploits_alt": out["alt|-"]["win"]["mean"] < .3,
        "exploits_wsls": out["wsls|-"]["win"]["mean"] < .45,
        "exploits_bias70": out["bias70|-"]["win"]["mean"] < .45,
    }
    ok = all(checks.values())
    lines += ["", "Null channel activation per channel (iid, M and O labels pooled):", ""]
    for k in range(9):
        lines.append(f"- channel {k}: {(out['iid|M']['channel_activation'][k] + out['iid|O']['channel_activation'][k]) / 2:.4f}")
    lines += ["", f"Null envelope (iid, {env['n_iid_sessions']} sessions): single session 95% "
                  f"[{env['session_q025']:.3f}, {env['session_q975']:.3f}]; mean of 4 sessions 95% "
                  f"[{env['mean4_q025']:.3f}, {env['mean4_q975']:.3f}]; runs z 95% [{env['runs_z_q025']:.2f}, {env['runs_z_q975']:.2f}]",
              "", "Checks: " + ", ".join(f"{k} {'PASS' if v else 'FAIL'}" for k, v in checks.items()),
              "", f"Overall: {'PASS' if ok else 'FAIL'}"]
    os.makedirs(os.path.join(HERE, "calibration"), exist_ok=True)
    with open(os.path.join(HERE, "calibration", "calibration_results.json"), "w", newline="\n") as fo:
        json.dump(dict(results=out, null_envelope=env, checks=checks, all_ok=ok), fo, indent=1)
    with open(os.path.join(HERE, "calibration", "calibration_summary.md"), "w", encoding="utf-8", newline="\n") as fo:
        fo.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
